def scrubbed(env: dict[str, str] | os._Environ[str] | None = None) -> dict[str, str]:
    base = os.environ if env is None else env
    return {k: v for k, v in base.items() if not k.startswith(("ANTHROPIC_", "CLAUDE_CODE_USE_", "T13_")) and k != "AWS_BEARER_TOKEN_BEDROCK"}


