def stage_import(target: Target, out: Path, scratch: Path, env: dict[str, str]) -> dict[str, Any]:
    """S1: rules-first import of the pinned copy, then ``review emit``."""
    src = scratch / "source"
    target.materialise(src)
    (src / "t13_adapter.py").write_text(target.harness)
    imp = out / "import"
    shutil.rmtree(imp, ignore_errors=True)
    ienv = {**env, "PYTHONPATH": os.pathsep.join([env["PYTHONPATH"], str(src)])}
    py = sys.executable
    cmds = {
        "import": [py, "-m", "lattice.importer", str(src), "--package", target.package, "--app-factory", "t13_adapter:make_app", "--rules-only", "--out", str(imp)],
        "emit": [py, "-m", "lattice.importer", "review", str(imp), "emit"],
    }
    runs: dict[str, Any] = {}
    for name, cmd in cmds.items():
        p = subprocess.run(cmd, cwd=scratch, env=ienv, capture_output=True, text=True, timeout=1800)
        tail = (p.stdout + p.stderr)[-3000:].replace(str(scratch), "<scratch>")
        runs[name] = {"rc": p.returncode, "tail": tail}
        if p.returncode != 0:
            last = [ln for ln in tail.splitlines() if ln.strip()][-2:]
            return stage("S1", "fail", why=f"{name} exited {p.returncode}: " + " | ".join(x.strip() for x in last), runs=runs)
    report = json.loads((imp / "report.json").read_text())
    summary = {"framework": report["rules"]["framework"], "summary": report["rules"]["summary"], "unclear_profile": report.get("unclear")}
    if not (imp / "spec.py").is_file():
        return stage("S1", "fail", why="emit wrote no spec.py", runs=runs, report=summary)
    return stage("S1", "pass", runs=runs, report=summary, spec_sha256=sha((imp / "spec.py").read_bytes()))


def protected_list(target: Target, repo: Path) -> list[str]:
    files: list[str] = list(PROJECT_FILES)
    for root in target.protect_roots:
        p = repo / root
        if p.is_file():
            files.append(root)
            continue
        for f in sorted(p.rglob("*")):
            r = f.relative_to(repo).as_posix()
            if f.is_file() and "__pycache__" not in f.parts and r != target.rebuild_file:
                files.append(r)
    return [f for f in dict.fromkeys(files) if (repo / f).exists() or f in PROJECT_FILES]


def build_repo(target: Target, scratch: Path, imp: Path) -> tuple[Path, str, Path, list[str]]:
    """The agent's repository (one commit, the base), the reference text of the rebuilt file, the held-out tests."""
    repo = scratch / "build-repo"
    target.materialise(repo)
    reference = (repo / target.rebuild_file).read_text()
    holdout = scratch / "holdout"
    shutil.rmtree(holdout, ignore_errors=True)
    holdout.mkdir(parents=True)
    shutil.copytree(repo / "tests", holdout / "tests", ignore=shutil.ignore_patterns("__pycache__"))
    for rel in target.strip:
        p = repo / rel
        if p.is_dir() and not p.is_symlink():
            shutil.rmtree(p)
        elif p.exists() or p.is_symlink():
            p.unlink()
    (repo / target.rebuild_file).write_text(target.scaffold)
    for name in ("spec.py", "profile.py", "natives.py", "spec_meta.json"):
        if (imp / name).is_file():
            shutil.copy2(imp / name, repo / name)
    (repo / "harness.py").write_text(target.harness)
    (repo / "check.sh").write_text(CHECK_SH.format(app_dir=target.app_dir, package=target.package))
    (repo / "check.sh").chmod(0o755)
    (repo / "CONTEXT.md").write_text(CONTEXT.format(title=target.title, file=target.rebuild_file, factory=target.factory, domain=target.domain))
    ignore = repo / ".gitignore"
    ignore.write_text((ignore.read_text() if ignore.is_file() else "") + "\n# T1-3\n__pycache__/\n.pytest_cache/\nmetrics/\n*.db\n")
    protected = protected_list(target, repo)
    (repo / "studio.toml").write_text(STUDIO_TOML.format(name=target.name, max_rounds=MAX_ROUNDS, model=MODEL, protected=json.dumps(protected)))
    for args in (["init", "-q", "-b", "main"], ["add", "-A"], ["commit", "-q", "-m", "T1-3 base: scaffold + spec"]):
        subprocess.run(["git", "-c", "user.name=t13", "-c", "user.email=t13@example.invalid", *args], cwd=repo, check=True, capture_output=True)
    return repo, reference, holdout, protected


def verify(repo: Path, base: str, tip: str, cmd: str, env: dict[str, str], scratch: Path) -> dict[str, Any]:
    from lattice.studio.cleanverify import verify as clean_verify

    v = clean_verify(repo, base, tip, cmd, runs=1, gates=["./check.sh"], env=env, parent=scratch / "verify", timeout=1800)
    d = v.as_dict()
    d["output_tail"] = d["output_tail"][-2500:].replace(str(scratch), "<scratch>")
    d["tree_path"] = d["tree_path"].replace(str(scratch), "<scratch>")
    return d


def side_commit(repo: Path, branch: str, files: dict[str, str]) -> str:
    """A commit on `branch` from main with `files` written (calibration and tests), main left checked out."""
    git(repo, "checkout", "-q", "-B", branch, "main", check=True)
    try:
        for rel, text in files.items():
            (repo / rel).write_text(text)
        git(repo, "commit", "-q", "-am", f"T1-3 {branch}", check=True)
        return git(repo, "rev-parse", "HEAD", check=True)
    finally:
        git(repo, "checkout", "-q", "main", check=True)


def stage_fixture(target: Target, out: Path, scratch: Path, env: dict[str, str]) -> tuple[dict[str, Any], dict[str, Any]]:
    """S2: the build repo and its calibration (no model)."""
    repo, reference, holdout, protected = build_repo(target, scratch, out / "import")
    base = git(repo, "rev-parse", "HEAD", check=True)
    ref_tip = side_commit(repo, "t13-calibration-reference", {target.rebuild_file: reference})
    held = target.holdout_cmd(holdout)
    calib: dict[str, Any] = {}
    for name, tip in (("reference", ref_tip), ("scaffold", base)):
        lat = verify(repo, base, tip, "./check.sh", env, scratch)
        ho = verify(repo, base, tip, held, env, scratch)
        calib[name] = {"lattice_gate": lat, "held_out": {**ho, "counts": pytest_counts(ho["output_tail"])}}
    ok = calib["reference"]["lattice_gate"]["passed"] and calib["reference"]["held_out"]["passed"] and not calib["scaffold"]["held_out"]["passed"]
    ctx = {"repo": repo, "base": base, "reference": reference, "holdout": holdout, "held_cmd": held, "protected": protected}
    st = stage(
        "S2",
        "pass" if ok else "fail",
        base=base,
        protected=len(protected),
        calibration=calib,
        lattice_gate_vacuous=bool(calib["scaffold"]["lattice_gate"]["passed"]),
        **({} if ok else {"why": "calibration: the reference must pass the Lattice gate and the held-out tests, the scaffold must fail the held-out tests"}),
    )
    return st, ctx


def fake_plan(target: Target, agent: str, reference: str, repo: Path) -> dict[str, Any]:
    if agent == "reference":
        return {"files": {target.rebuild_file: reference}, "summary": "fake agent: the reference file"}
    if agent == "noop":
        return {"files": {}, "summary": "fake agent: changed nothing"}
    if agent == "tamper":
        return {"files": {target.rebuild_file: reference, "spec.py": (repo / "spec.py").read_text() + "\n# tampered by the fake agent\n"}, "summary": "fake agent: edited the spec"}
    raise ValueError(f"unknown fake agent {agent!r}")


