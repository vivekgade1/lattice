def pytest_counts(text: str) -> dict[str, int]:
    """The counts of pytest's last summary line ("3 failed, 5 passed, 1 deselected in 0.2s")."""
    lines = [ln for ln in text.splitlines() if re.search(r"\b(passed|failed|error|errors|no tests ran)\b", ln)]
    last = lines[-1] if lines else ""
    out = {k: 0 for k in ("passed", "failed", "errors", "deselected")}
    for n, word in re.findall(r"(\d+) (passed|failed|errors?|deselected)", last):
        out["errors" if word.startswith("error") else word] = int(n)
    return out


