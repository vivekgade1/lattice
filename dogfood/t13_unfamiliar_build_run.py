@dataclass(frozen=True)
class Target:
    name: str
    title: str
    package: str
    app_dir: str
    rebuild_file: str
    factory: str
    harness: str
    scaffold: str
    holdout_files: tuple[str, ...]
    domain: str = ""
    strip: tuple[str, ...] = ("tests",)
    deselect: tuple[str, ...] = ()
    source_repo: Path | None = None
    source_rev: str | None = None
    source_dir: Path | None = None
    extra_site: Path | None = None
    protect_roots: tuple[str, ...] = field(default=())

    def available(self) -> tuple[bool, str]:
        if self.source_dir is not None:
            return (self.source_dir.is_dir(), f"{self.source_dir} is missing")
        assert self.source_repo is not None and self.source_rev is not None
        r = subprocess.run(["git", "-C", str(self.source_repo), "cat-file", "-e", f"{self.source_rev}^{{commit}}"], capture_output=True)
        if r.returncode != 0:
            return False, f"{self.source_repo} has no commit {self.source_rev}"
        if self.extra_site is not None and not self.extra_site.is_dir():
            return False, f"the app's venv {self.extra_site} is missing"
        return True, ""

    def materialise(self, dest: Path) -> None:
        """The pinned source, read only: ``git archive`` of the commit, or a copy of the directory."""
        shutil.rmtree(dest, ignore_errors=True)
        if self.source_dir is not None:
            shutil.copytree(self.source_dir, dest, ignore=shutil.ignore_patterns("__pycache__", ".pytest_cache"))
            return
        dest.mkdir(parents=True)
        arch = subprocess.run(["git", "-C", str(self.source_repo), "archive", str(self.source_rev)], capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "-C", str(dest)], input=arch, check=True)

    def holdout_cmd(self, holdout: Path) -> str:
        args = [*self.holdout_files, *(f"--deselect={d}" for d in self.deselect)]
        return f"cp -R {shlex.quote(str(holdout / 'tests'))} tests && python -m pytest -q -p no:cacheprovider " + " ".join(shlex.quote(a) for a in args)


