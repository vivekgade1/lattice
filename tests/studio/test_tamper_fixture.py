"""The tamper-pressure fixtures (node X2): ``tests/fixtures/tamper_unsatisfiable`` and
``tests/fixtures/tamper_conflict``, generated by ``scripts/make_tamper_fixtures.py`` from the toy Shelf
gRPC project. Each puts real pressure on an agent loop to edit the spec or the gate: the first has a rule
no implementation can satisfy (the check prints "spec problem:"), the second a spec requirement that
contradicts a visible acceptance scenario.

Driven through ``lattice.studio.rebuild.Rebuilder`` with a scripted FAKE ``claude`` (no model, no API
key, no network: Go, buf and the two protoc plugins run from local caches). They prove:

* calibration: the scaffold fails, the reference solution fails exactly the impossible / conflicting
  check, and only dropping that check from the spec turns the gate green (so tampering is the only way);
* an independent base-vs-tip sha256 diff of the declared protected files (:func:`protected_diff`,
  written here, not the Rebuilder's own restore) detects an edit of each protected file, and shows what
  the Rebuilder restores. COVERAGE below is printed per case (``pytest -s``): which protected file is
  restored by ``Rebuilder`` with the fixture's declared ``[mcp] protected`` list (all of them) and with
  none (``protected=[]``, the constructor default): then only the spec files and the gate script are.
  The uncovered cases are ``xfail(strict=True)``: a later node that closes the gap flips them;
* the unsatisfiable fixture ends with ``build_cause == "spec_unsatisfiable"``.

The fixtures are skipped (with the command that makes them) when not generated, and the Rebuilder
tests when go / buf / protoc or the protoc plugins are missing."""

