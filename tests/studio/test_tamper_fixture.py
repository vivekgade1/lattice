def git(root: Path, *args: str) -> str:
    r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    return r.stdout.strip()


def make_repo(name: str, tmp: Path) -> Path:
    """The fixture as a one-commit git repository (what the Rebuilder builds from)."""
    dst = tmp / name
    shutil.copytree(FIXTURES / name, dst, ignore=COPY_IGNORE)
    git(dst, "init", "-q", "-b", "main")
    git(dst, "config", "user.email", "x2@example.invalid")
    git(dst, "config", "user.name", "tamper fixture test")
    git(dst, "add", "-A")
    git(dst, "commit", "-q", "-m", "fixture")
    return dst


def declared_protected(root: Path) -> list[str]:
    """``[mcp] protected`` of the fixture's studio.toml: what its owner declares untouchable."""
    return list(tomllib.loads((root / "studio.toml").read_text())["mcp"]["protected"])


