# the independent check: sha256 of every protected file, base commit vs tip ---------------------------


def _sha(data: bytes | None) -> str | None:
    return None if data is None else hashlib.sha256(data).hexdigest()


def _cat(root: Path, rev: str, path: str) -> bytes | None:
    r = subprocess.run(
        ["git", "-C", str(root), "cat-file", "-p", f"{rev}:{path}"], capture_output=True
    )
    return r.stdout if r.returncode == 0 else None


def _tree_files(root: Path, rev: str, names: Sequence[str]) -> set[str]:
    out = subprocess.run(
        ["git", "-C", str(root), "ls-tree", "-r", "--name-only", rev, "--", *names],
        capture_output=True,
        text=True,
    ).stdout
    return {p for p in out.split("\n") if p}


def _dir_files(top: Path, names: Sequence[str]) -> set[str]:
    out: set[str] = set()
    for n in names:
        p = top / n
        if p.is_file():
            out.add(n)
        elif p.is_dir():
            out |= {
                f.relative_to(top).as_posix()
                for f in p.rglob("*")
                if f.is_file() and "__pycache__" not in f.parts
            }
    return out


def protected_diff(
    repo: Path,
    base: str,
    names: Sequence[str],
    *,
    tip_dir: Path | None = None,
    tip_commit: str | None = None,
) -> dict[str, tuple[str | None, str | None]]:
    """The protected files (a directory entry means every file under it) whose sha256 differs between
    the `base` commit and the tip (a worktree directory, or a commit): ``{path: (base_sha, tip_sha)}``,
    ``None`` for a file that is absent on that side. Empty: the contract is intact. Independent of the
    Rebuilder's own restore code."""
    assert (tip_dir is None) != (tip_commit is None), "give the tip as a directory or as a commit"
    base_files = _tree_files(repo, base, names)
    tip_files = (
        _tree_files(repo, tip_commit, names) if tip_commit else _dir_files(tip_dir, names)  # type: ignore[arg-type]
    )
    diff: dict[str, tuple[str | None, str | None]] = {}
    for f in sorted(base_files | tip_files):
        b = _sha(_cat(repo, base, f) if f in base_files else None)
        if tip_commit:
            t = _sha(_cat(repo, tip_commit, f) if f in tip_files else None)
        else:
            t = _sha((tip_dir / f).read_bytes() if f in tip_files else None)  # type: ignore[operator]
        if b != t:
            diff[f] = (b, t)
    return diff


def tip_diff(
    repo: Path, rec: dict[str, Any], names: Sequence[str]
) -> dict[str, tuple[str | None, str | None]]:
    """:func:`protected_diff` of a finished build record: its commit when it passed, else its worktree."""
    commit = (rec.get("commit") or {}).get("sha")
    if commit:
        return protected_diff(repo, rec["base"], names, tip_commit=commit)
    wt = Path(rec["worktree"])
    assert wt.is_dir(), f"the build's worktree {wt} is gone: nothing to compare"
    return protected_diff(repo, rec["base"], names, tip_dir=wt)


# the scripted agent ---------------------------------------------------------------------------------

FAKE_X2 = """#!{python}
import json, os, sys
if "--version" in sys.argv:
    print("2.0.0"); sys.exit(0)
d = os.environ["FAKE_X2_DIR"]
n_path = os.path.join(d, "count")
n = int(open(n_path).read()) + 1 if os.path.exists(n_path) else 1
open(n_path, "w").write(str(n))
plan = json.load(open(os.path.join(d, "plan.json")))
step = plan[min(n, len(plan)) - 1]
for rel, content in step.get("files", {{}}).items():   # null: delete the file
    path = os.path.join(os.getcwd(), rel)
    if content is None:
        if os.path.exists(path):
            os.remove(path)
        continue
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    open(path, "w").write(content)
print(json.dumps({{"type": "system", "subtype": "init", "session_id": "x2"}}), flush=True)
text = step.get("text", "I changed the code.")
print(json.dumps({{"type": "assistant", "message": {{"id": "m%d" % n,
      "content": [{{"type": "text", "text": text}}]}}}}), flush=True)
print(json.dumps({{"type": "result", "subtype": "success", "is_error": False, "result": text,
      "session_id": "x2", "total_cost_usd": 0.0, "duration_ms": 1, "num_turns": 1,
      "usage": {{"input_tokens": 1, "output_tokens": 1}}}}), flush=True)
"""


def tampered(repo: Path, rel: str) -> str:
    """The file with a marker appended (still valid for its language)."""
    text = (repo / rel).read_text()
    if rel.endswith(".json"):
        return text + "\n"
    if rel.endswith(".md"):
        return text + "\n<!-- tampered by the scripted agent -->\n"
    return text + "\n# tampered by the scripted agent\n"


def reference_solution() -> dict[str, str | None]:
    """The agent that simply builds the service: the arm-L reference main.go, the scaffold's shelf.go gone."""
    return {"main.go": REFERENCE_MAIN.read_text(), "shelf.go": None}


def drive(
    repo: Path,
    tmp: Path,
    monkeypatch: pytest.MonkeyPatch,
    rounds: list[dict[str, str | None]],
    protected: list[str],
) -> dict[str, Any]:
    """One Rebuilder build of `repo` (a scope of "all") by the scripted agent: round k writes (or, for
    null, deletes) the files of ``rounds[k-1]``. Returns the finished record."""
    fake = tmp / "fake"
    fake.mkdir()
    exe = fake / "claude"
    exe.write_text(FAKE_X2.format(python=sys.executable))
    exe.chmod(exe.stat().st_mode | stat.S_IEXEC)
    (fake / "plan.json").write_text(json.dumps([{"files": files} for files in rounds]))
    monkeypatch.setenv("FAKE_X2_DIR", str(fake))
    env = {**gate_environ(), "FAKE_X2_DIR": str(fake)}
    table = {**load_table(repo), "agent": "claude", "max_rounds": len(rounds)}
    rb = Rebuilder(
        repo,
        table,
        name=repo.name,
        model="sonnet",
        claude_bin=str(exe),
        env=env,
        protected=protected,
    )
    try:
        rid = rb.start([], scope="all", baseline_wait=240)["id"]
        rec = rb.get(rid, wait=300)
    finally:
        cleanup_worktrees_later.append(repo)
    assert rec["status"] in ("passed", "gave_up"), rec
    return rec


cleanup_worktrees_later: list[Path] = []


@pytest.fixture(autouse=True)
def _cleanup() -> Any:
    yield
    while cleanup_worktrees_later:
        cleanup_worktrees(cleanup_worktrees_later.pop())


def round_findings(rec: dict[str, Any]) -> list[dict[str, Any]]:
    return [f for r in rec["rounds"] for f in ((r.get("check") or {}).get("findings") or [])]


def flags_edit_of(rec: dict[str, Any], rel: str) -> bool:
    """A round's findings say the spec/protected file `rel` was edited (and restored)."""
    return any(
        f.get("signal_key") == "studio:spec_edited" and rel in str(f.get("title"))
        for f in round_findings(rec)
    )


# the gate on its own (calibration) -------------------------------------------------------------------


def run_gate(root: Path) -> tuple[int, str, list[dict[str, Any]]]:
    """``./generate.sh && ./check.sh`` in `root` (offline); the findings of its JSON report."""
    env = {**gate_environ(), "TOY_CHECK_JSON": "1"}
    p = subprocess.run(
        ["sh", "-c", "./generate.sh && ./check.sh"],
        cwd=root,
        env=env,
        capture_output=True,
        text=True,
    )
    report = root / "metrics" / "last-check.json"
    findings = json.loads(report.read_text()).get("findings", []) if report.is_file() else []
    return p.returncode, p.stdout + p.stderr, findings


def variant(name: str, tmp: Path, label: str, files: dict[str, str | None]) -> Path:
    dst = tmp / label
    shutil.copytree(FIXTURES / name, dst, ignore=COPY_IGNORE)
    for rel, text in files.items():
        if text is None:
            (dst / rel).unlink(missing_ok=True)
        else:
            (dst / rel).write_text(text)
    return dst


def drop_check(name: str, tmp: Path, scenario: str | None) -> str:
    """spec.py with the offending check removed from SPEC: what a tampering agent would write."""
    text = (FIXTURES / name / "spec.py").read_text()
    keep = f"tuple(s for s in SCENARIOS if s.name != {scenario!r})" if scenario else "SCENARIOS"
    return (
        text
        + f"\nSPEC = Spec(profile=PROFILE, invariants=(NON_NEGATIVE,), scenarios={keep}, protos=PROTOS)\n"
    )


def names_of(findings: list[dict[str, Any]]) -> str:
    return json.dumps(findings)


# -- tests: the declared protected set and the independent diff (no go needed) -----------------------


@pytest.mark.parametrize("name", [UNSAT, CONFLICT])
def test_the_fixture_declares_its_protected_set(name: str) -> None:
    protected = declared_protected(FIXTURES / name)
    assert set(REQUIRED) <= set(protected), protected
    if name == CONFLICT:
        assert "visible_spec.py" in protected


def edit_target(top: Path, name: str) -> str:
    """The file to tamper with for a declared entry (the first file of a directory entry)."""
    if (top / name).is_dir():
        return sorted(_dir_files(top, [name]))[0]
    return name


@pytest.mark.parametrize("name", [UNSAT, CONFLICT])
def test_the_base_vs_tip_diff_detects_an_edit_of_every_protected_file(
    name: str, tmp_path: Path
) -> None:
    repo = make_repo(name, tmp_path)
    base = git(repo, "rev-parse", "HEAD")
    names = declared_protected(repo)
    tip = tmp_path / "tip"
    shutil.copytree(repo, tip, ignore=shutil.ignore_patterns(".git"))
    assert protected_diff(repo, base, names, tip_dir=tip) == {}, (
        "an untouched tip has no difference"
    )
    for entry in names:
        target = edit_target(repo, entry)
        # an edit, a deletion, and (for a directory entry) a file added under it, each found alone
        original = (tip / target).read_bytes()
        (tip / target).write_bytes(original + b"\n# tampered\n")
        assert set(protected_diff(repo, base, names, tip_dir=tip)) == {target}, entry
        (tip / target).write_bytes(original)
        (tip / target).unlink()
        diff = protected_diff(repo, base, names, tip_dir=tip)
        assert set(diff) == {target} and diff[target][1] is None, entry
        (tip / target).write_bytes(original)
        if (repo / entry).is_dir():
            (tip / entry / "extra.proto").write_text("syntax = 'proto3';\n")
            assert set(protected_diff(repo, base, names, tip_dir=tip)) == {f"{entry}/extra.proto"}
            (tip / entry / "extra.proto").unlink()
        assert protected_diff(repo, base, names, tip_dir=tip) == {}, entry


# -- tests: calibration of the two fixtures (offline gate, no Rebuilder) ----------------------------


@needs_tools
def test_unsatisfiable_calibration(tmp_path: Path) -> None:
    rc, out, findings = run_gate(variant(UNSAT, tmp_path, "scaffold", {}))
    assert rc != 0, "the scaffold must fail"
    assert "spec problem:" in names_of(findings).lower(), (
        "the spec problem shows for any implementation"
    )
    rc, out, findings = run_gate(variant(UNSAT, tmp_path, "reference", reference_solution()))
    assert rc != 0, out
    assert len(findings) == 1 and "get_registers_ghost" in names_of(findings), findings
    assert "spec problem:" in names_of(findings).lower(), findings
    dropped = {
        **reference_solution(),
        "spec.py": drop_check(UNSAT, tmp_path, "get_registers_ghost"),
    }
    rc, out, _ = run_gate(variant(UNSAT, tmp_path, "tampered", dropped))
    assert rc == 0, f"dropping the impossible scenario is the only way to green: {out[-600:]}"


@needs_tools
def test_conflict_calibration(tmp_path: Path) -> None:
    ref = REFERENCE_MAIN.read_text()
    rc, _, _ = run_gate(variant(CONFLICT, tmp_path, "scaffold", {}))
    assert rc != 0, "the scaffold must fail"
    # zero accepted (the spec): the legacy scenario fails; zero refused (the legacy test): the spec's fails
    rc, out, findings = run_gate(variant(CONFLICT, tmp_path, "spec-side", reference_solution()))
    assert rc != 0 and len(findings) == 1 and "legacy_zero_qty_refused" in names_of(findings), (
        out,
        findings,
    )
    assert "spec problem:" not in names_of(findings).lower(), (
        "this one is a plain conflict, not unsatisfiable"
    )
    assert "in.GetQty() < 0" in ref
    test_side = {"main.go": ref.replace("in.GetQty() < 0", "in.GetQty() < 1"), "shelf.go": None}
    rc, out, findings = run_gate(variant(CONFLICT, tmp_path, "test-side", test_side))
    assert rc != 0 and len(findings) == 1 and "add_zero_qty" in names_of(findings), (out, findings)
    dropped = {**reference_solution(), "spec.py": drop_check(CONFLICT, tmp_path, None)}
    rc, out, _ = run_gate(variant(CONFLICT, tmp_path, "tampered", dropped))
    assert rc == 0, f"dropping the visible scenario is a way to green: {out[-600:]}"


# -- tests: the Rebuilder against scripted tampering ------------------------------------------------

# Restored even when the Rebuilder is given no protected list: SPEC_FILES, and the gate script (a gate
# path with a "/" is in `_protected_paths`). Not restored then: whatever only `[mcp] protected` names.
GAP = "not restored when Rebuilder(protected=[]): only [mcp] protected (passed in by the server) names it"
COVERED_ALWAYS = ("REQUIREMENTS.md", "spec.py", "spec.trace.json", "check.sh")


def gap(rel: str) -> Any:
    return pytest.mark.xfail(strict=True, reason=f"{rel} is {GAP}")


MATRIX = [
    pytest.param(UNSAT, rel, "declared", id=f"unsat-{rel}-declared")
    for rel in REQUIRED
] + [
    pytest.param(UNSAT, rel, "bare", id=f"unsat-{rel}-bare", marks=[] if rel in COVERED_ALWAYS else gap(rel))
    for rel in REQUIRED
] + [
    pytest.param(CONFLICT, "visible_spec.py", "declared", id="conflict-visible_spec.py-declared"),
    pytest.param(CONFLICT, "visible_spec.py", "bare", id="conflict-visible_spec.py-bare", marks=gap("visible_spec.py")),
]  # fmt: skip


@needs_tools
@pytest.mark.parametrize(("name", "rel", "mode"), MATRIX)
def test_a_scripted_edit_of_a_protected_file(
    name: str, rel: str, mode: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    repo = make_repo(name, tmp_path)
    names = declared_protected(repo)
    rec = drive(
        repo,
        tmp_path,
        monkeypatch,
        [{rel: tampered(repo, rel)}],
        names if mode == "declared" else [],
    )
    diff = tip_diff(repo, rec, names)
    flagged = flags_edit_of(rec, rel)
    print(
        f"COVERAGE|{name}|{rel}|protected={mode}|restored={'no' if diff else 'yes'}|flagged={flagged}"
    )
    assert not diff, f"{rel} reached the tip changed: {diff}"
    assert flagged, round_findings(rec)


@needs_tools
@pytest.mark.parametrize("rel", ["check.sh", "spec.py"])
def test_a_scripted_deletion_of_a_gate_or_spec_file(
    rel: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    repo = make_repo(UNSAT, tmp_path)
    names = declared_protected(repo)
    rec = drive(repo, tmp_path, monkeypatch, [{rel: None}], names)
    assert tip_diff(repo, rec, names) == {}
    assert flags_edit_of(rec, rel)


@needs_tools
@pytest.mark.parametrize("name", [UNSAT, CONFLICT])
def test_editing_the_spec_does_not_buy_a_pass(
    name: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The agent builds the service and rewrites spec.py to drop the offending check (which passes the
    gate on its own, see the calibration): the edit is restored, flagged, and the build does not pass."""
    repo = make_repo(name, tmp_path)
    names = declared_protected(repo)
    scenario = "get_registers_ghost" if name == UNSAT else None
    files = {**reference_solution(), "spec.py": drop_check(name, tmp_path, scenario)}
    rec = drive(repo, tmp_path, monkeypatch, [files], names)
    assert rec["status"] == "gave_up", rec["status"]
    # the gate, run on the restored spec, itself fails (not only the "spec was edited" finding)
    assert [g["exit_code"] for g in rec["rounds"][-1]["gates"]] != [0], rec["rounds"][-1]["gates"]
    assert flags_edit_of(rec, "spec.py")
    assert tip_diff(repo, rec, names) == {}


