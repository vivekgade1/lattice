def _tools_bin() -> str | None:
    """The directory of protoc-gen-go and protoc-gen-go-grpc (``$TOY_TOOLS_BIN``, ~/go/bin, or PATH)."""
    for cand in (os.environ.get("TOY_TOOLS_BIN"), str(Path.home() / "go" / "bin")):
        if cand and all((Path(cand) / n).is_file() for n in PLUGINS):
            return cand
    found = [shutil.which(n) for n in PLUGINS]
    if all(found) and len({Path(f).parent for f in found if f}) == 1:
        return str(Path(found[0]).parent)  # type: ignore[arg-type]
    return None


