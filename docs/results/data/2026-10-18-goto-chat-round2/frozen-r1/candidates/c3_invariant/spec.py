def seed(*habits, completions=(), nudges=(), targets=None, **extra):
    """Habits with their first habit_targets row, plus extra rows."""
    rows = {"habits": list(habits),
            "habit_targets": targets if targets is not None else [
                {"id": 100 + i, "habit_id": h["id"], "target_count": h["target_count"],
                 "effective_from": period_start(h["start_date"], h["period"])}
                for i, h in enumerate(habits)]}
    if completions:
        rows["completions"] = list(completions)
    if nudges:
        rows["nudges"] = list(nudges)
    rows.update({k: list(v) for k, v in extra.items()})
    return rows


