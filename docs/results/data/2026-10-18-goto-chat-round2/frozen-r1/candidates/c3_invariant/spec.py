def batch_dates(start_id, habit_n, first, count):
    d0 = dt.date.fromisoformat(first)
    return [{"id": u(start_id + i), "habit_id": u(habit_n),
             "date": (d0 + dt.timedelta(days=i)).isoformat()} for i in range(count)]


